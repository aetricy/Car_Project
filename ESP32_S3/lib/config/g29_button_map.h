// ==========================================
// G29 BUTTON BITMAP (32-Bit Bitmask)
// ==========================================
#define BTN_CROSS          (1UL << 0)  // Cross (X) Button
#define BTN_SQUARE         (1UL << 1)  // Square Button
#define BTN_CIRCLE         (1UL << 2)  // Circle Button
#define BTN_TRIANGLE       (1UL << 3)  // Triangle Button

#define BTN_PADDLE_RIGHT   (1UL << 4)  // Right Paddle (Shift Up)
#define BTN_PADDLE_LEFT    (1UL << 5)  // Left Paddle (Shift Down)

#define BTN_R2             (1UL << 6)
#define BTN_L2             (1UL << 7)
#define BTN_R3             (1UL << 8)
#define BTN_L3             (1UL << 9)

#define BTN_SHARE          (1UL << 10)
#define BTN_OPTIONS        (1UL << 11)
#define BTN_PS             (1UL << 12) // PlayStation Button

#define BTN_PLUS           (1UL << 13) // Rotary Dial + Button
#define BTN_MINUS          (1UL << 14) // Rotary Dial - Button
#define BTN_ENTER          (1UL << 15) // Rotary Dial Center Button (Enter)
#define BTN_DIAL_RIGHT     (1UL << 16) // Rotary Dial Clockwise Turn
#define BTN_DIAL_LEFT      (1UL << 17) // Rotary Dial Counter-Clockwise Turn

// D-Pad (Directional Buttons)
#define BTN_DPAD_UP        (1UL << 18)
#define BTN_DPAD_DOWN      (1UL << 19)
#define BTN_DPAD_RIGHT     (1UL << 20)
#define BTN_DPAD_LEFT      (1UL << 21)