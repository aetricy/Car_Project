// ==========================================
// G29 TUŞ HARİTASI (32 Bit Maske)
// ==========================================
#define BTN_CROSS          (1UL << 0)  // X Tuşu
#define BTN_SQUARE         (1UL << 1)  // Kare Tuşu
#define BTN_CIRCLE         (1UL << 2)  // Yuvarlak Tuşu
#define BTN_TRIANGLE       (1UL << 3)  // Üçgen Tuşu

#define BTN_PADDLE_RIGHT   (1UL << 4)  // Sağ Kulakçık (Shift Up)
#define BTN_PADDLE_LEFT    (1UL << 5)  // Sol Kulakçık (Shift Down)

#define BTN_R2             (1UL << 6)
#define BTN_L2             (1UL << 7)
#define BTN_R3             (1UL << 8)
#define BTN_L3             (1UL << 9)

#define BTN_SHARE          (1UL << 10)
#define BTN_OPTIONS        (1UL << 11)
#define BTN_PS             (1UL << 12) // PlayStation Tuşu

#define BTN_PLUS           (1UL << 13) // Kırmızı Çark İçi +
#define BTN_MINUS          (1UL << 14) // Kırmızı Çark İçi -
#define BTN_ENTER          (1UL << 15) // Kırmızı Çark Ortası (Dial Enter)
#define BTN_DIAL_RIGHT     (1UL << 16) // Kırmızı Çark Sağa Dönüş
#define BTN_DIAL_LEFT      (1UL << 17) // Kırmızı Çark Sola Dönüş

// D-Pad (Yön Tuşları)
#define BTN_DPAD_UP        (1UL << 18)
#define BTN_DPAD_DOWN      (1UL << 19)
#define BTN_DPAD_RIGHT     (1UL << 20)
#define BTN_DPAD_LEFT      (1UL << 21)